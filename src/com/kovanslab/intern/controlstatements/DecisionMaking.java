package com.kovanslab.intern.controlstatements;

public class DecisionMaking {
    public static void main(String[] args) {
        int score = 85;

        if (score >= 90) {
            System.out.println("Grade A");
        } else if (score >= 75) {
            System.out.println("Grade B");
        } else {
            System.out.println("Grade C");
        }
    }
}

